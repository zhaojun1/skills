def find_answer(question: str) -> str:
    """根据问题找到最匹配的答案"""
    question_lower = question.lower()
    best_match = None
    max_score = 0

    for qa in QA_DATABASE:
        score = sum(1 for kw in qa["keywords"] if kw in question_lower)
        if score > max_score:
            max_score = score
            best_match = qa

    if best_match and max_score > 0:
        return f"**{best_match['question']}**\n\n{best_match['answer']}"
    return None


def analyze_phenomenon(phenomenon: str) -> str:
    """分析恋爱现象"""
    pheno_lower = phenomenon.lower()
    for key, value in PHENOMENA.items():
        if any(kw in pheno_lower for kw in value.get("keywords", [key])):
            result = f"## {value['现象']}\n\n"
            result += "### 可能原因\n"
            for i, d in enumerate(value["诊断"], 1):
                result += f"{i}. {d}\n"
            result += "\n### 解决方案\n"
            for i, s in enumerate(value["解决方案"], 1):
                result += f"{i}. {s}\n"
            if "金句" in value:
                result += f"\n> 💡 **金句**：{value['金句']}"
            return result
    return None


def get_methodology(topic: str = None) -> str:
    """获取方法论指导"""
    if topic:
        topic_lower = topic.lower()
        for key, value in METHODOLOGY.items():
            if any(kw in topic_lower for kw in [key, value["title"]]):
                result = f"## {value['title']}\n\n"
                result += f"**核心**：{value['summary']}\n\n"
                result += f"**原理**：\n{value['core']}\n\n"
                result += f"**案例**：\n{value['example']}\n\n"
                result += "**实用技巧**：\n"
                for i, tip in enumerate(value.get("tips", []), 1):
                    result += f"{i}. {tip}\n"
                return result

    # 返回所有方法论列表
    result = "## 📚 方法论总览\n\n"
    for key, value in METHODOLOGY.items():
        result += f"### {value['title']}\n{value['summary']}\n\n"
    return result


